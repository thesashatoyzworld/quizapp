export interface ShotPair {
  question: string;
  answer: string;
}

export interface Correction {
  question: string;
  draft: string;
  sent: string;
}

export function renderExamples(pairs: ShotPair[], corrections: Correction[]): string {
  const parts: string[] = [];
  if (pairs.length) {
    parts.push(
      '## Как Саша отвечал на похожее (живые пары из группы)\n\n' +
        pairs.map((p) => `ученик: ${p.question}\nСаша: ${p.answer}`).join('\n\n'),
    );
  }
  if (corrections.length) {
    parts.push(
      '## Где Саша поправил черновик (учись на разнице)\n\n' +
        corrections
          .map((c) => `вопрос: ${c.question}\nчерновик: ${c.draft}\nСаша отправил: ${c.sent}`)
          .join('\n\n'),
    );
  }
  return parts.join('\n\n');
}

/** Ответ модели. Не JSON или без полей → считаем, что черновика нет. */
export function parseReply(raw: string): { reply: string | null; note: string } {
  const start = raw.indexOf('{');
  const end = raw.lastIndexOf('}');
  if (start === -1 || end <= start) return { reply: null, note: 'модель ответила не JSON' };
  try {
    const obj = JSON.parse(raw.slice(start, end + 1)) as { reply?: unknown; note?: unknown };
    const reply = typeof obj.reply === 'string' && obj.reply.trim() ? obj.reply.trim() : null;
    const note = typeof obj.note === 'string' ? obj.note.trim() : '';
    return { reply: reply ? stripDashes(reply) : null, note };
  } catch {
    return { reply: null, note: 'модель ответила битым JSON' };
  }
}

/**
 * Служебное, которое модель иногда пишет ученику вопреки правилам: «не вижу
 * файл», «скинь ещё раз», «цену не подтверждаю». Такой черновик не годится,
 * Саша получит вопрос без него.
 */
const LEAK = /не ви(жу|дел)|не откры(л|ва)|скинь (ещ[её] раз|текстом|скрином)|не подтвержда|не ко мне|по цене/i;

export function leaksMeta(reply: string): boolean {
  return LEAK.test(reply);
}

/** Саша не пишет длинное тире. Модель всё равно иногда вставляет. */
export function stripDashes(s: string): string {
  return s.replace(/\s—\s/g, ' - ').replace(/—/g, '-');
}

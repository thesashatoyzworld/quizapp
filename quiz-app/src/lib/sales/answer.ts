// дальше. Не отправляет сам — решение и отправка остаются за человеком.

const anthropic = new Anthropic();

/** Один следующий шаг: что отправить, почему и где человек стоит. */
export type SalesStep = {
  message: string;
  why: string;
  stage: string;
  callSasha: string | null;
};

export type SalesAnswer = SalesStep & {
  found: boolean;
  who: string;
  waiting: string | null;
  thread: SalesThread | null;
};

const SYSTEM = `Ты ведёшь переписки за Сашу и доводишь человека до оплаты.

С тобой разговаривает Саша или его ассистент. Ты даёшь ОДНО следующее
сообщение — то, которое отправят человеку как есть. Не советы, не варианты
на выбор, не рассуждение: готовый текст.

Ниже вся база: продукты, цены, приёмы, материалы, разбор живых переписок.
Отвечай только по ней. Цифры, ссылки и схемы оплаты берутся оттуда. Нет
в базе — «уточню у Саши», а не догадка.

## Что мы продаём и в каком порядке

Лестница идёт СВЕРХУ ВНИЗ. Сначала предлагается дорогое, вниз спускаемся
только после отказа или когда по фактам человеку рано.

| Что | Сколько | Кому |
|---|---|---|
| «Делаем за вас» | 400-500 тыс. за 3 месяца | доход от 500 тыс. в месяц. Здесь зови Сашу |
| Индивидуальный формат, 1-1 | 300 000 | хочет лично с Сашей, тянет по деньгам. Состав уточняется, поэтому зови Сашу |
| Групповой формат, 3 месяца | 130 000 одним платежом, помесячно 50 000 × 3 | есть продукт, есть клиенты, есть чек. Основной чек по заявкам на менторство |
| Тариф 2 | 10 000 в месяц, пакетом 3 месяца 25 000 | не тянет 130к, но продукт есть и деньги в блоге нужны |
| Тариф 1 | 5 450 разово | нет продукта, нет клиентов, «возьму паузу подумать» |

Тариф 1 это не цель, а нижняя ступень. Не веди туда человека, который тянет
на 130к: у Саши так покупали фитнес-тренер, брокер, эзотерик, маркетолог.

Изнутри тарифа 1 всегда открыт апгрейд на тариф 2: доплата это 10 000 минус
уплаченное. Это твоя зона, Сашу звать не надо.

Тарифы 2 и 3 с улицы закрыты, там отбор. Дату открытия не называй, её нет.

## Как выбрать шаг

Смотри, где человек стоит, и делай ровно один шаг вперёд.

1. **Не знаем ситуацию.** Спроси самый конкретный факт: чек, сколько клиентов,
   что продаёт. Один вопрос. Бей в противоречие анкеты, если оно есть.
2. **Знаем ситуацию, не знаем прогрет ли.** Спроси про материалы. Ниша совпала
   с готовым кейсом — назови кейс и дай ссылку вместо общего вопроса.
3. **Не прогрет.** Отправь материал под нишу со ссылкой и фразой из документа
   «Материалы». Цену не называй.
4. **Прогрет и есть чем платить.** Собери оффер: три месяца работы, что входит,
   стоимость 130 000 одним платежом или 50 000 помесячно, и вопрос «что думаешь?».
   Обе цифры называются вместе, одной строкой.
5. **Отказался от 130к.** Спусти на ступень: тариф 2 с окупаемостью, потом
   тариф 1 с рассрочкой 227 в месяц без переплаты.
6. **Последними писали мы, человек молчит.** Короткое напоминание одним словом
   и только если прошло больше дня. Не сочиняй новое сообщение.

## Приёмы, которых нет в наших переписках, но они работают

Подробности в документе «Продажи в переписке».

**Вопрос про последствия — перед ценой.** Не «ты потеряешь год», а «а если
оставить как есть, через год что?». Утверждение давит, вопрос продаёт.

**Отзеркаливание.** Повтори два-три последних слова человека вопросом:
«не идёт трафик» → «совсем не идёт?». Дешевле умного вопроса и работает лучше.

**Ярлык.** Назови то, что человек чувствует, но не сказал: «похоже, ты уже
пробовал и обжёгся».

**Возражение вслух до него.** «скорее всего сейчас думаешь, что дорого и что
сам справишься» — названное нами возражение теряет силу.

**«Как» и «что» вместо «почему».** «что мешает начать сейчас?» вместо «почему
не начал?»: «почему» звучит как допрос.

**Вопрос-картинка перед оффером:** «если через три месяца это решится — что
поменяется?» Из его ответа и собирается оффер.

## Как продавать

Это главное. Ошибки ниже разобраны самим Сашей на чужом созвоне.

**Не делай выводы за человека.** Вывод, который сделал ты, он слушает
с мыслью «я и сам могу». Вывод, к которому он пришёл сам, продаёт. Задавай
вопрос вместо утверждения.

**Лови якоря — его собственные слова** о том, где болит и сколько это длится.
«2,5 месяца не могу взять себя в руки» это якорь. В оффере и в возражениях
опирайся на его слова, а не на свои формулировки.

**Копай до настоящей мотивации.** За «хочу больше подписчиков» стоит другое.
Спроси, зачем ему это, и что изменится.

**Мост к продаже:** «я не сказал ничего нового, ты это и так знал. Но сам
не начал. Зачем тебе я?» Человек сам приходит к тому, что без внешней
поддержки не сдвинется.

**Оффер собирается из результатов, а не из действий,** и через то, что важно
ему. Список того, что входит, ценность не поднимает.

**Цена переводится в клиентов.** Не «это выгодно», а «нам нужно два клиента,
чтобы ты окупил затраты на меня».

**«Дорого» разбирается вопросом**, а не скидкой: на что рассчитывал, почему
дорого. Только потом арифметика.

**Не дожимай.** Упёрся — короткая фраза без обиды, дверь открытой. Из базы:
рилсмейкер вернулся через три недели, фитнес-тренер через двадцать минут.

**Закрытие — вопрос с выбором,** а не «оплатите»: «фулл или разобьём?»,
«отправить ссылку для доплаты?».

**Не отпускай бессрочно.** «Подумаю» закрывается либо вопросом «что смущает»,
либо конкретной датой возврата за ответом.

**Молчание — самая дорогая ошибка.** Прямой вопрос про деньги без ответа
это потерянный человек: у нас так ушли двое. Если цену называть рано, дай
вилку («от 5 450 за курс до 130 000 за три месяца работы») и следом вопрос
про его ситуацию. Уходить в «расскажи сначала о себе» без цифр нельзя.

**Возвращать пропавших по каденции:** сутки, три дня, неделя. Каждое касание
несёт новое — кейс, мысль, вопрос. Последнее закрывает петлю: «понял, тогда
не буду отвлекать, вернёшься — пиши». Оно и получает ответ чаще всего.

## Если мы долго молчали

Тебе говорят, сколько человек ждёт ответа. Больше четырёх часов — первой
строкой коротко скажи, почему была пауза, и сразу переходи к делу:

> много заявок было, только разгребаю
> вчера был завал по заявкам, добрался только сейчас

Одна строка, деловым тоном. Не «извини, пожалуйста, за долгое ожидание»,
не объяснение на абзац, не обещания «больше такого не повторится»: Саша не
оправдывается. Причина всегда рабочая — заявок много, разбирал очередь,
были созвоны.

Меньше четырёх часов — не упоминай паузу вообще, это нормальный темп
переписки. И не начинай с неё, если человек ждёт ответа на прямой вопрос
про деньги: тогда сначала пауза одной строкой, а дальше сразу ответ, а не
новые вопросы.

## Как писать

- строчные буквы, короткие строки, мысль на строку, точки в конце не ставятся
- НИКАКОГО длинного тире. Саша его не пишет никогда: вместо него дефис,
  запятая или новая строка. Это видно сразу и выдаёт, что писал не он
- ровно один вопрос в сообщении
- вопрос всегда про то, что человек сам написал
- никакого канцелярита и «доброго времени суток»
- мат допустим, но редко и по делу
- назвал кейс — дай ссылку целиком, с меткой из документа «Материалы»
- первое сообщение всегда показывает, что анкету прочитали

## Чего не делать

- называть цену тому, кто ничего не смотрел
- вести на тариф 1 того, кто тянет на групповой формат
- предлагать бесплатный разбор или диагностику: их нет, созвон 1-1 это часть
  продукта, а не предпродажа
- первым заговаривать про возврат денег
- предлагать схему оплаты, которой нет в базе
- продавать тарифы как «попробовать месяц»
- описывать устройство работы своими словами: «всё индивидуально», «нет
  фиксированной цены» — это неправда, состав и цены фиксированные
- имитировать голосовые Саши

## Как читать переписку

Строки с пометкой «кодовое слово в комментарии под постом» — не разговор,
а нажатие кнопки.

Строка «привет) анкета на менторство - Имя, #номер» — человек пришёл с формы
по кнопке. Это начало разговора, а не содержательная реплика.

Последними писали МЫ и ответа нет — предлагай напоминание, а не ответ
на несказанное.

## Когда звать Сашу

Заполни callSasha: доход от 500 тысяч, страх «наставник пропадёт», «я не смогу
как в кейсе», просьба о бесплатном разборе, давление на тему возврата, запрос
на индивидуальный формат. Первые два Саша отвечает голосом, и это только его
работа. Сообщение всё равно дай: до передачи есть что написать.`;

const SCHEMA = {
  type: 'object',
  properties: {
    message: { type: 'string', description: 'готовое сообщение целиком, отправляется как есть' },
    why: { type: 'string', description: 'одной строкой: почему этот шаг сейчас' },
    stage: {
      type: 'string',
      description: 'где человек стоит: не знаем ситуацию | знаем ситуацию | греется | прогрет | внутри тарифа 1 | молчит',
    },
    callSasha: {
      type: ['string', 'null'],
      description: 'если нужен Саша — почему; иначе null',
    },
  },
  required: ['message', 'why', 'stage', 'callSasha'],
  additionalProperties: false,
} as const;

function waitingFor(thread: SalesThread): string | null {
  const last = thread.messages[thread.messages.length - 1];
  if (!last || last.side !== 'client') return null;
  const hours = Math.round((Date.now() - last.createdAt * 1000) / 3_600_000);
  if (hours < 1) return 'меньше часа';
  if (hours < 24) return `${hours} ч`;
  return `${Math.round(hours / 24)} дн`;
}

/**
 * Чему научились на правках Саши.
 *
 * Пара «предложили — отправили» говорит о промпте больше, чем любая теория:
 * видно, что он вычёркивает, что дописывает и где мы промахиваемся тоном.
 * Берём последние, потому что они отражают сегодняшние цены и формулировки.
 */
async function recentCorrections(take = 6): Promise<string | null> {
  const rows = await prisma.salesCorrection.findMany({
    orderBy: { createdAt: 'desc' },
    take,
    select: { suggested: true, sent: true },
  });
  if (!rows.length) return null;

  const cases = rows
    .reverse()
    .map(
      (r, i) => `Случай ${i + 1}.
Предлагали:
${r.suggested}

Саша отправил вместо этого:
${r.sent}`,
    )
    .join('\n\n---\n\n');

  return `# Правки Саши на живых переписках

Ниже то, что мы предлагали, и то, что Саша отправил на самом деле. Это не
примеры для копирования дословно, а показания, чем предложенное не годилось:
длина, тон, лишние объяснения, не тот шаг лестницы, преждевременная цена.

Разбирая новую переписку, воспроизводи эти поправки, а не повторяй ошибки.

${cases}`;
}

/**
 * Сколько человек ждёт и надо ли объяснять паузу.
 *
 * Указание идёт в самом запросе, а не только в системном промпте: там оно
 * теряется через раз, а «извини, разгребал заявки» первой строкой Саша
 * просил ставить обязательно.
 */
function waitedLine(seconds?: number | null): string {
  if (!seconds || seconds < 3600) return '';

  const human =
    seconds < 24 * 3600 ? `${Math.round(seconds / 3600)} ч` : `${Math.round(seconds / 86400)} дн`;
  if (seconds < 4 * 3600) return `Ждёт ответа: ${human}`;

  return `Ждёт ответа: ${human}

ВАЖНО: мы молчали дольше четырёх часов. Первой строкой коротко скажи, почему
была пауза (много заявок, разгребал очередь, были созвоны), и сразу переходи
к делу. Одна строка, без извинений на абзац и без обещаний.`;
}

/**
 * Что написать дальше по готовой переписке. Источник неважен: инста-директ
 * приходит из ChatPlace, личка рабочего аккаунта — из телеграма, база
 * и промпт для обоих одни.
 */
export async function suggestFromThread(params: {
  /** Что известно о человеке: ник, анкета, воронка. */
  about: string;
  /** Переписка строками «[время] ЧЕЛОВЕК/МЫ: текст». */
  rendered: string;
  /** Куда вести ответ — если Саша задал направление руками. */
  steer?: string | null;
  /** Сколько человек ждёт ответа, в секундах. */
  waitingSeconds?: number | null;
}): Promise<SalesStep> {
  // Чему научились на правках: что предлагали и что Саша отправил вместо.
  const lessons = await recentCorrections();

  const res = await anthropic.messages.create({
    model: 'claude-sonnet-5',
    max_tokens: 6000,
    system: [
      { type: 'text' as const, text: SYSTEM },
      { type: 'text' as const, text: SALES_KB, cache_control: { type: 'ephemeral' as const } },
      // Правки идут ПОСЛЕ базы и вне кэша: они меняются часто, а база нет.
      ...(lessons ? [{ type: 'text' as const, text: lessons }] : []),
    ],
    messages: [
      {
        role: 'user',
        content: `Человек:
${params.about || 'ничего не известно'}
${waitedLine(params.waitingSeconds)}

Переписка:
${params.rendered}
${
  params.steer
    ? `
Саша сказал, куда вести ответ:
${params.steer}

Это указание, а не пожелание: следуй ему, но по-прежнему одним сообщением
и по правилам базы. Если оно противоречит фактам переписки — всё равно делай
как сказано, а сомнение вынеси в поле why.`
    : ''
}
Что написать дальше?`,
      },
    ],
    output_config: { format: { type: 'json_schema', schema: SCHEMA } },
  });

  if (process.env.SALES_DEBUG) {
    console.error('[sales] stop_reason:', res.stop_reason, '· output:', res.usage.output_tokens);
  }

  const empty: SalesStep = { message: '', why: '', stage: '', callSasha: null };
  const block = res.content.find((b) => b.type === 'text');
  if (!block || block.type !== 'text') return empty;
  try {
    return JSON.parse(block.text) as SalesStep;
  } catch {
    console.error('[sales] ответ модели не разобрался как json');
    return empty;
  }
}

/** Ник человека → что ему написать дальше. Инста-директ. */
export async function suggestReply(handle: string): Promise<SalesAnswer> {
  const thread = await findThread(handle);
  if (!thread) {
    return {
      found: false,
      who: handle,
      waiting: null,
      message: '',
      why: '',
      stage: '',
      callSasha: null,
      thread: null,
    };
  }

  const { lead, messages } = thread;
  const about = [
    lead.handle ? `ник: @${lead.handle}` : null,
    lead.name ? `имя в инстаграме: ${lead.name}` : null,
    lead.keyword ? `пришёл по кодовому слову: ${lead.keyword}` : null,
    lead.automationName ? `воронка: ${lead.automationName}` : null,
    lead.formKind ? `ВНИМАНИЕ: уже оставил анкету (${lead.formKind}), из холодной ему не пишем` : null,
    lead.note ? `заметка ассистента: ${lead.note}` : null,
  ]
    .filter(Boolean)
    .join('\n');

  const parsed = await suggestFromThread({ about, rendered: renderThread(messages) });

  return {
    found: true,
    who: lead.handle ? `@${lead.handle}` : lead.name || handle,
    waiting: waitingFor(thread),
    ...parsed,
    thread,
  };
}

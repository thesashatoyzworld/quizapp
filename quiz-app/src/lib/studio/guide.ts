/** The whole guide as markdown, for the MCP tool get_onboarding. Without the key. */
export function guideMarkdown(opts: { libraryOpen: boolean }): string {
  const parts = guideSections(opts).map((sec) => `## ${sec.title}\n\n${sec.md}`);
  parts.push([
    '## Как отвечать по инструментам',
    '- Карточки и копии: list_schedule (можно query: «бабушка», «мама»). У копий variant и copyNo.',
    '- ТЗ, комментарии, цифры одной карточки: get_item.',
    '- Сменить этап: set_stage (text, edit, ready, skip). «Вышло» только через attach_post со ссылкой.',
    '- Какие правки сработали: get_variant_stats. Правила: list_rules.',
    '- Позиции, пруфы, проблемы: search_library, потом get_library_entry. Оговорки в записи соблюдать.',
  ].join('\n'));
  return `# Студия: как пользоваться\n\n${parts.join('\n\n')}\n`;
}

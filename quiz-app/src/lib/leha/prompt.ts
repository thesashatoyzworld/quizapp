/**
 * Промпт Лёхи. Правила обобщённые, без цитат из переписки: репозиторий
 * публичный. Живые примеры Саши подкладываются из LEHA_EXAMPLES на сервере,
 * в коде их нет.
 */

export const LEHA_SYSTEM = `Ты пишешь первое сообщение от лица Саши (мужчина, наставник по контенту и продажам для экспертов) человеку, который только что заполнил анкету на менторство или в лист ожидания и сам написал в личку телеграма. Задача сообщения одна: чтобы человек ответил и рассказал факты о своём деле.

Правила:
1. Первая строка: короткое имя, как его зовут свои, с заглавной буквы, и «привет». Если имени нет, просто «привет».
2. Только на «ты». Никаких «добрый день», «здравствуйте», «пожалуйста», «расскажите».
3. Скажи, что видел анкету: «видел твою анкету на менторство», «вижу анкету», «смотрю анкету». Для листа ожидания: «видел твою заявку в лист ожидания».
4. Отдельной строкой мостик «хотел уточнить».
5. Ровно один вопрос, в конце, со знаком «?».
6. Вопрос про деньги в его деле, а не про контент: сколько клиентов сейчас, какой чек, откуда идут клиенты, что из продуктов реально приносит деньги.
7. Если в анкете противоречие (доход есть, а продукта нет; подписчиков много, а дохода мало; пишет одно, отметил другое), вопрос бьёт прямо в него.
8. Опирайся на конкретную деталь из анкеты его же словами. Не выдумывай того, чего в анкете нет.
9. Если доход 500к+ или по анкете у человека всё хорошо, спроси прямо, где проблема или зачем ему работать с Сашей.
10. Ничего не продавать: без ссылок, цен, тарифов, продуктов, созвонов.
11. Не извиняться и не объяснять паузу.
12. Коротко: 2-4 строки, 80-160 знаков. Мысли разделяй пустой строкой. Строчные буквы, кроме имени. Точек в конце строк нет. Из смайлов только «)», и то не всегда.
13. О себе только в мужском роде: «видел», «посмотрел», «хотел».
14. Без длинного тире, без кавычек-ёлочек, без слов «уникальный», «давай разберёмся», «отличный вопрос».
15. Если человек в своём сообщении уже ответил на очевидный вопрос, не задавай его снова: спроси следующий факт.

Ответ: только текст сообщения, без пояснений и без кавычек вокруг.`;

export type LeadForPrompt = {
  id: number;
  kind: string | null;
  firstName: string | null;
  who: string | null;
  hasProduct: string | null;
  product: string | null;
  level: number | null;
  tried: string | null;
  want: string | null;
  income: string | null;
  hours: string | null;
  following: string | null;
  readiness: string | null;
  followers: string | null;
};

const KIND: Record<string, string> = {
  mentor: 'анкета на менторство',
  t2: 'заявка в лист ожидания тарифа 2',
  t3: 'заявка в лист ожидания тарифа 3',
};

/** Анкета и то, что человек успел написать, одним куском для модели. */
export function renderLead(lead: LeadForPrompt, said: string[]): string {
  const rows: [string, string | number | null][] = [
    ['что это', KIND[lead.kind || ''] || lead.kind || 'анкета на менторство'],
    ['имя', lead.firstName],
    ['кто', lead.who],
    ['свой продукт', [lead.hasProduct, lead.product].filter(Boolean).join(': ') || null],
    ['уровень в контенте (1-10)', lead.level],
    ['что пробовал', lead.tried],
    ['чего хочет через 3 месяца', lead.want],
    ['доход в месяц', lead.income],
    ['часов в неделю на блог', lead.hours],
    ['подписчиков в инстаграме', lead.followers],
    ['как давно читает Сашу', lead.following],
    ['готовность купить', lead.readiness],
  ];
  const anketa = rows
    .filter(([, v]) => v !== null && v !== undefined && String(v).trim() !== '')
    .map(([k, v]) => `${k}: ${String(v).trim()}`)
    .join('\n');
  const chat = said.map((t) => `> ${t.trim()}`).join('\n');
  return `АНКЕТА\n${anketa}\n\nЧТО ЧЕЛОВЕК НАПИСАЛ В ЛИЧКУ\n${chat || '> (пусто)'}\n\nНапиши первое сообщение Саши.`;
}

/** Примеры живых первых сообщений Саши: только из окружения, не из кода. */
export function systemWithExamples(examples: string | undefined = process.env.LEHA_EXAMPLES): string {
  const ex = (examples || '').trim();
  return ex ? `${LEHA_SYSTEM}\n\nПримеры того, как Саша на самом деле пишет первое сообщение:\n${ex}` : LEHA_SYSTEM;
}

export const MAX_LEN = 400;

/**
 * Привести ответ модели к сообщению или отказаться от него.
 * null: черновик нельзя показывать как готовый (ссылка, цена, пусто, простыня).
 */
export function cleanReply(raw: string): { text: string | null; problem: string | null } {
  let t = (raw || '').trim();
  t = t.replace(/^["«»“”']+|["«»“”']+$/g, '').trim();
  t = t.replace(/\s*—\s*/g, ' - ');
  t = t.replace(/\n{3,}/g, '\n\n');
  if (!t) return { text: null, problem: 'пусто' };
  if (/https?:\/\/|t\.me\/|www\./i.test(t)) return { text: null, problem: 'в тексте ссылка' };
  if (/\d[\d\s]*(₽|руб|тыс|000)/i.test(t)) return { text: null, problem: 'в тексте цена' };
  if (t.length > MAX_LEN) return { text: null, problem: 'слишком длинно' };
  if (!t.includes('?')) return { text: t, problem: 'нет вопроса' };
  return { text: t, problem: null };
}

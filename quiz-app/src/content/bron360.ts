/** Строка про места: живое число броней, без накрутки. */
export function seatsLine(taken: number): string {
  if (taken <= 0) return '';
  if (taken < 5) return 'первые места уже бронируют.';
  return `осталось ${Math.max(BRON_SEATS - taken, 0)} из ${BRON_SEATS} мест по 10 000.`;
}


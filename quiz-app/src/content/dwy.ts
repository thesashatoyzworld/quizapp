// ─────────────────────────────────────────────────────────────
// Режимы анкеты. Вопросы во всех одинаковые — меняется шапка, метка лида
// и то, какие поля обязательны.
//   mentor — менторство, ссылка из шапки профиля (режим по умолчанию)
//   t2/t3  — лист ожидания закрытых тарифов «Нового уровня контента»
// Так в одном месте видно, кто пришёл на менторство, а кто ждёт набора.
// ─────────────────────────────────────────────────────────────
export const DWY_KINDS = ['mentor', 't2', 't3'] as const;
export type DwyKind = (typeof DWY_KINDS)[number];

/** Все поля анкеты в порядке формы. */
export const DWY_FIELDS = [
  'name', 'contact', 'phone', 'instagram',
  'who', 'hasProduct', 'level', 'tried', 'want', 'income', 'hours',
] as const;
export type DwyField = (typeof DWY_FIELDS)[number];

export type DwyMode = {
  title: string;
  argument: string[];
  thanks: string[];
  /** Заголовок уведомления в Telegram — по нему Саша отличает поток. */
  notice: string;
  /**
   * Поля, без которых анкету не отправить. Единственный источник правды:
   * и форма, и эндпоинт читают этот список отсюда.
   */
  required: readonly DwyField[];
  /** Строка над формой, если обязательных полей меньше, чем вопросов. */
  formNote?: string;
};

// Телефон и инстаграм не обязательны нигде. Юзернейм люди правда пишут
// с опечатками, но номер на холодном трафике отдают неохотно — теряем
// больше, чем страхуем.
const MENTOR_REQUIRED = [
  'name', 'contact', 'who', 'hasProduct', 'level', 'tried', 'want', 'income', 'hours',
] as const;

// У листа ожидания цена входа другая: человек просит напомнить о наборе,
// а не проходит отбор. Спрашиваем то же самое, но обязательны имя и контакт —
// остальное к сентябрю всё равно поменяется, а стена из девяти вопросов
// отсекает тех, кто пришёл с уже прочитанного оффера.
const WAITLIST_REQUIRED = ['name', 'contact'] as const;


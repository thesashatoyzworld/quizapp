import { test } from 'node:test';
import assert from 'node:assert/strict';
import { pickTerms } from './terms';

test('берёт редкие слова вопроса, частые и неизвестные корпусу выкидывает', () => {
  const df = new Map([
    ['контент', 400],
    ['нумеролог', 3],
    ['карусел', 60],
    ['закреп', 12],
  ]);
  assert.deepEqual(pickTerms(['контент', 'нумеролог', 'закреп', 'карусел', 'абракадабр'], df, 2000), [
    'нумеролог',
    'закреп',
    'карусел',
  ]);
});

test('повторы, цифры и короткие основы не идут в запрос', () => {
  const df = new Map([['оффер', 5], ['х3', 1], ['да', 1]]);
  assert.deepEqual(pickTerms(['оффер', 'оффер', 'х3', 'да'], df, 1000), ['оффер']);
});

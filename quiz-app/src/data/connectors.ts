// Deep merge function for content personalization
function deepMerge(base: ConnectorsContent, overrides: ContentOverrides): ConnectorsContent {
  const result = { ...base };

  if (overrides.preQualifier) {
    result.preQualifier = { ...base.preQualifier, ...overrides.preQualifier };
  }

  if (overrides.hero) {
    result.hero = { ...base.hero, ...overrides.hero };
  }

  if (overrides.beliefShift) {
    result.beliefShift = { ...base.beliefShift, ...overrides.beliefShift };
  }

  if (overrides.firstDays) {
    result.firstDays = {
      ...base.firstDays,
      ...(overrides.firstDays.subtitle && { subtitle: overrides.firstDays.subtitle }),
      ...(overrides.firstDays.items && { items: overrides.firstDays.items }),
    };
  }

  if (overrides.weeks4to8) {
    result.weeks4to8 = {
      ...base.weeks4to8,
      ...(overrides.weeks4to8.subtitle && { subtitle: overrides.weeks4to8.subtitle }),
      ...(overrides.weeks4to8.items && { items: overrides.weeks4to8.items }),
    };
  }

  if (overrides.important) {
    result.important = { ...base.important, ...overrides.important };
  }

  if (overrides.forYouIf) {
    result.forYouIf = {
      ...base.forYouIf,
      ...(overrides.forYouIf.title && { title: overrides.forYouIf.title }),
      ...(overrides.forYouIf.items && { items: overrides.forYouIf.items }),
    };
  }

  if (overrides.cta) {
    result.cta = { ...base.cta, ...overrides.cta };
  }

  return result;
}

// Export function to get content based on archetype type
export function getConnectorsContent(type?: string): ConnectorsContent {
  // If no type or invalid type, return base content
  if (!type || !validTypes.includes(type as ConnectorType)) {
    return baseContent;
  }

  // Return merged content for valid archetype
  const archetypeType = type as ConnectorType;
  return deepMerge(baseContent, archetypeOverrides[archetypeType]);
}


// Приветственный пакет тарифа 2: первое, что человек видит после того, как
// доступ привязался к его телеграму.
//
// Что делать первым, здесь намеренно НЕ написано: маршрут человек получит после
// интервью, и он у каждого свой. Здесь только где что лежит.
//
// Правки копирайта — только сюда. НЕ ставить длинное тире.

/**
 * Запасная ссылка в группу. Обычно её не нужно: бот выписывает персональную
 * прямо в момент приветствия. Env остаётся на случай, если бота выгнали из
 * группы или у него отобрали право приглашать.
 */
export const GROUP_INVITE = process.env.UROVEN_GROUP_INVITE || '';

export function welcomeText(groupInvite?: string | null): string {
  const invite = groupInvite || GROUP_INVITE;
  const items = [
    '*кабинет.* это твоя полка, там сразу всё. с чего начинать именно тебе, скажу после интервью.',
    // Ссылки нет — пункт про группу просто выпадает, нумерация не съезжает.
    invite && `*группа.* туда падают анонсы созвонов и записи, ссылка личная и работает один раз: ${invite}`,
    '*интервью.* сейчас задам несколько вопросов про тебя и твой контент. по ответам соберу маршрут: что смотреть, в каком порядке, и что делать после каждого куска.',
  ].filter(Boolean) as string[];

  return `готово, ты внутри ⚡

тариф 2 открыт. все материалы лежат в кабинете: курс по уровням, премиум-библиотека воркшопов, разборы, записи созвонов.

как двигаемся дальше:

${items.map((line, i) => `${i + 1}. ${line}`).join('\n\n')}`;
}

export const WELCOME_BUTTON = '🚪 Открыть кабинет';

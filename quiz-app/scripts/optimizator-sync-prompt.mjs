// Regenerates src/lib/optimizator/system.ts and output-schema.ts from the
// reels-optimizer prompt folder (system.md + output-schema.json). Re-run after
// every prompt change there; the cabinet never reads that repo at runtime.
//
// Run: node scripts/optimizator-sync-prompt.mjs ../../reels-optimizer/prompts/kallaway
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/optimizator-sync-prompt.mjs <path to prompts/kallaway>');
  process.exit(1);
}
const dir = resolve(src);
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'optimizator');

const system = readFileSync(join(dir, 'system.md'), 'utf8').replace(/\r\n/g, '\n');
const schema = JSON.parse(readFileSync(join(dir, 'output-schema.json'), 'utf8'));

function git(...args) {
  try {
    return execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8' }).trim();
  } catch {
    return '?';
  }
}
const ref = `branch ${git('branch', '--show-current')} (${git('log', '-1', '--format=%h', '--', 'system.md', 'output-schema.json')})`;
const title = (system.match(/^#\s+(.+)$/m) || [])[1] || 'system.md';

writeFileSync(
  join(out, 'system.ts'),
  `// GENERATED by scripts/optimizator-sync-prompt.mjs, do not edit by hand.
// Source: reels-optimizer repo, ${ref}, prompts/kallaway/system.md
// (${title}).
// Server-only: never import this module from a 'use client' file, the prompt must not reach the browser bundle.

export const SYSTEM_PROMPT: string = ${JSON.stringify(system)};
`,
);

writeFileSync(
  join(out, 'output-schema.ts'),
  `// GENERATED by scripts/optimizator-sync-prompt.mjs, do not edit by hand.
// Source: reels-optimizer repo, ${ref}, prompts/kallaway/output-schema.json
// Used on the server to strip keys the schema does not declare.

import type { JsonSchema } from "./strip";
export const OUTPUT_SCHEMA: JsonSchema = ${JSON.stringify(schema, null, 2)};
`,
);

console.log(`synced ${title} / ${schema.$id} (${ref})`);

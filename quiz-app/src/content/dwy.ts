// ─────────────────────────────────────────────────────────────
// Режимы анкеты. Вопросы во всех одинаковые — меняется шапка, метка лида
// и то, какие поля обязательны.
//   mentor — менторство, ссылка из шапки профиля (режим по умолчанию)
//   t2/t3  — лист ожидания закрытых тарифов «Нового уровня контента»
// Так в одном месте видно, кто пришёл на менторство, а кто ждёт набора.
// ─────────────────────────────────────────────────────────────
export const DWY_KINDS = ['mentor', 't2', 't3'] as const;
export type DwyKind = (typeof DWY_KINDS)[number];

/** Все поля анкеты в порядке формы. */
export const DWY_FIELDS = [
  'name', 'contact', 'phone', 'instagram',
  'who', 'hasProduct', 'level', 'tried', 'want', 'income', 'hours',
] as const;
export type DwyField = (typeof DWY_FIELDS)[number];

export type DwyMode = {
  title: string;
  argument: string[];
  thanks: string[];
  /** Заголовок уведомления в Telegram — по нему Саша отличает поток. */
  notice: string;
  /**
   * Поля, без которых анкету не отправить. Единственный источник правды:
   * и форма, и эндпоинт читают этот список отсюда.
   */
  required: readonly DwyField[];
  /**
   * Что видно сразу, до кнопки. Остальные вопросы прячутся за ссылкой:
   * пометки «необязательно» стену из одиннадцати вопросов не разбирают,
   * человек всё равно видит длину и уходит.
   */
  visible: readonly DwyField[];
  /** Подпись ссылки, раскрывающей остальные вопросы. */
  moreLabel?: string;
  /** Подпись кнопки: в лист ожидания записываются, анкету отправляют. */
  submitLabel: string;
  /**
   * Куда человек уходит сразу после отправки. Бот не может написать первым:
   * ни Bot API, ни business-подключение не умеют превращать «@ник» в чат,
   * начать разговор вправе только человек. Поэтому телеграм открываем сами,
   * а дальше переписку ведёт бот, подключённый к аккаунту.
   */
  handoff?: {
    /** Аккаунт, которому пишут. Без собаки. */
    account: string;
    /** Строка под «спасибо», пока открывается телеграм. */
    note: string;
    /** Запасная кнопка: если переход не сработал, ткнуть можно руками. */
    button: string;
  };
};


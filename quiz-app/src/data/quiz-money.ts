export type MoneyScores = Record<MoneyBlock, number>;

export interface MoneyResult {
  primary: MoneyBlock | 'vse-horosho';
  secondary: MoneyBlock | null;
  scores: MoneyScores;
  overlapPercent: number; // % перекрытия топ-блока (для датчика на result-экране)
}

// Сумма баллов по блокам.
export function calculateScores(answers: number[]): MoneyScores {
  const scores: MoneyScores = {
    nadryv: 0,
    izbeganie: 0,
    paralich: 0,
    ugozhdenie: 0,
    utechka: 0,
    zazhim: 0,
  };

  answers.forEach((answer, index) => {
    const rule = scoringRules[index + 1]?.[answer];
    if (rule) {
      BLOCK_ORDER.forEach((block, col) => {
        scores[block] += rule[col];
      });
    }
  });

  return scores;
}

// Определение результата: топ-1 основной + топ-2 доп (если не шум).
// Если у топ-1 меньше порога — исход «всё хорошо».
export function determineResult(answers: number[], scores: MoneyScores): MoneyResult {
  const ranked = [...BLOCK_ORDER].sort((a, b) => scores[b] - scores[a]);
  const top = ranked[0];
  const second = ranked[1];

  const totalPossible = Object.keys(scoringRules).length * 35; // грубая нормировка
  const overlapPercent = Math.min(95, Math.round((scores[top] / totalPossible) * 100));

  if (scores[top] < VSE_HOROSHO_THRESHOLD) {
    return { primary: 'vse-horosho', secondary: null, scores, overlapPercent };
  }

  return {
    primary: top,
    secondary: scores[second] >= SECONDARY_MIN ? second : null,
    scores,
    overlapPercent,
  };
}

// slug result-экрана по результату (для редиректа на /r/<slug>.html)
export function resultSlug(result: MoneyResult): string {
  return result.primary === 'vse-horosho'
    ? VSE_HOROSHO.resultSlug
    : blockMeta[result.primary].resultSlug;
}

// Приветственный пакет тарифа 3: первое, что человек видит после того, как
// доступ привязался к его телеграму.
//
// До 16.09.2026 у тарифа 3 приветствия не было вовсе: человек за 150-300к
// получал первым сообщением вопрос анкеты и больше ничего — ни куда идти,
// ни что ему открыто, ни ссылки в группу.
//
// Что делать первым, здесь намеренно НЕ написано: маршрут человек получит
// картой после интервью, и он у каждого свой. Здесь только где что лежит.
//
// Правки копирайта — только сюда. НЕ ставить длинное тире.

/**
 * @param groupInvite именная ссылка в группу; пустая = пункт просто выпадает
 * @param withIntake  false, если анкета уже пройдена: тогда вместо интервью
 *                    человеку обещаем карту (так бывает у оплат мимо кассы,
 *                    где доступ и анкета случились раньше приветствия)
 */
export function welcomeTextT3(groupInvite?: string | null, withIntake = true): string {
  const items = [
    '*кабинет.* твоя полка: курс по уровням, премиум-библиотека воркшопов, разборы, записи групповых созвонов. что смотреть именно тебе, скажу картой.',
    // Ссылки нет — пункт про группу просто выпадает, нумерация не съезжает.
    groupInvite && `*группа.* туда падают анонсы созвонов и записи, ссылка личная и работает один раз: ${groupInvite}`,
    withIntake
      ? '*интервью.* сейчас задам вопросы про тебя, блог и деньги. отвечай голосовыми, из живой речи вытащить можно в разы больше. по ответам соберу твою карту.'
      : '*карта.* по твоим ответам собираю маршрутную карту: где ты сейчас, куда идём, что делаешь по неделям. придёт отдельным сообщением, жить будет в кабинете, в разделе «Карта».',
    '*созвоны.* групповые по расписанию, анонсы в группе, записи в кабинете. личный один на один назначаем отдельно, напишу сам.',
  ].filter(Boolean) as string[];

  return `готово, ты внутри ⚡

тариф 3, делаем вместе. личные созвоны со мной, групповые созвоны, маршрутная карта и весь кабинет.

как двигаемся дальше:

${items.map((line, i) => `${i + 1}. ${line}`).join('\n\n')}`;
}

export const WELCOME_BUTTON_T3 = '🚪 Открыть кабинет';

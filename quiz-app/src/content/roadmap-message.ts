// Сообщение человеку, когда Саша одобрил его карту. Правки копирайта — сюда.
//
// Тон повторяет то, что Саша написал первому человеку с картой руками:
// строчными, строка на мысль, без «уважаемый» и без обещаний результата.
// Личная часть одна: `mainTakeaway`, её пишет сборщик карты по анкете.
//
// НЕ ставить длинное тире.

export interface RoadmapMessageParams {
  steps: number;
  tasksThisWeek: number;
  mainTakeaway: string;
}

export function roadmapReadyMessage(p: RoadmapMessageParams): string {
  const week =
    p.tasksThisWeek === 1
      ? 'на этой неделе одна задача'
      : `на этой неделе ${p.tasksThisWeek} задачи`;

  return [
    'посмотрел твою анкету. спасибо, что наговорил, а не отделался парой строк: по голосу видно сильно больше',
    '',
    'собрал тебе маршрут на месяц: что смотреть, в каком порядке и что делать после каждого куска. он уже лежит в кабинете, раздел <b>«Карта»</b>',
    '',
    'что там внутри:',
    '',
    `• путь из ${p.steps} ступеней и отметка, где ты стоишь сейчас`,
    '• задачи по неделям, у каждой кнопка сразу в нужный материал',
    '• твои цифры на старте, чтобы через месяц было с чем сравнить',
    '',
    'отмечай сделанное галочкой, я это вижу',
    '',
    `${week}, начни сверху`,
    '',
    p.mainTakeaway.trim(),
  ].join('\n');
}

